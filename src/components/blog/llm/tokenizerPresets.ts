function piecesFromRounds(
  rounds: readonly (readonly TokenPiece[])[],
): readonly TokenPiece[] {
  const last = rounds.at(-1);
  if (last === undefined) throw new Error('piecesFromRounds: rounds is empty');
  return last;
}

